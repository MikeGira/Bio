// Guards against the "code scanning configuration error" the security overview
// shows when a scanner (e.g. checkov) is removed from a workflow but its old
// analyses linger — GitHub keeps expecting the tool and flags it as erroring.
// GitHub's documented remedy is to delete the stale analyses for that tool.
//
// Detection is cadence-relative, not name-based: whichever tools are still
// wired up keep producing fresh analyses (the "heartbeat"); a tool whose newest
// analysis has fallen far behind that heartbeat is orphaned and auto-cleared.
// A tool that is actively producing analyses but reporting an `error` is a
// different problem (a broken-but-live scan) — flagged for a human, never deleted.

const GH_TOKEN = process.env.GH_TOKEN;
const REPO = process.env.REPO;
// How far a tool's newest analysis may lag the freshest tool before it is
// treated as orphaned. Generous enough that a slow weekly scanner is never
// mistaken for removed.
const STALE_DAYS = Number(process.env.CS_STALE_DAYS || 14);
const MAX_PAGES = Number(process.env.CS_MAX_PAGES || 20);
const LABEL = 'code-scanning-health';

if (!GH_TOKEN) { console.error('Missing GH_TOKEN'); process.exit(1); }
if (!REPO) { console.error('Missing REPO'); process.exit(1); }

const API = `https://api.github.com/repos/${REPO}`;
const HEADERS = {
  Authorization: `Bearer ${GH_TOKEN}`,
  Accept: 'application/vnd.github+json',
  'X-GitHub-Api-Version': '2022-11-28',
};

async function gh(path, options = {}) {
  return fetch(path.startsWith('http') ? path : `${API}${path}`, {
    ...options,
    headers: { ...HEADERS, ...(options.body ? { 'Content-Type': 'application/json' } : {}), ...options.headers },
  });
}

// Newest-first. Group by tool: newest/oldest timestamps, the newest analysis id
// (delete entry point), and whether any analysis on the default branch errored.
async function collectTools() {
  const tools = new Map();
  for (let page = 1; page <= MAX_PAGES; page++) {
    const res = await gh(`/code-scanning/analyses?per_page=100&page=${page}`);
    if (res.status === 404) return tools; // code scanning never configured
    if (!res.ok) throw new Error(`List analyses failed: ${res.status} ${await res.text()}`);
    const rows = await res.json();
    if (rows.length === 0) break;
    for (const a of rows) {
      const name = a.tool?.name ?? 'unknown';
      const t = tools.get(name) ?? { name, newest: 0, newestId: null, count: 0, errored: false };
      const ts = Date.parse(a.created_at);
      if (ts > t.newest) { t.newest = ts; t.newestId = a.id; }
      t.count++;
      if (a.error && a.error.trim() && a.ref === 'refs/heads/main') t.errored = true;
      tools.set(name, t);
    }
    if (rows.length < 100) break;
  }
  return tools;
}

// Delete an entire tool's analyses by walking next_analysis_url from its newest
// entry. confirm_delete=true is required to remove the last analysis in a set.
async function deleteToolAnalyses(newestId) {
  let url = `${API}/code-scanning/analyses/${newestId}?confirm_delete=true`;
  let deleted = 0;
  while (url) {
    const res = await gh(url, { method: 'DELETE' });
    if (!res.ok) throw new Error(`Delete failed: ${res.status} ${await res.text()}`);
    deleted++;
    const body = await res.json();
    url = body.next_analysis_url ? `${body.next_analysis_url}?confirm_delete=true` : null;
  }
  return deleted;
}

async function getOpenIssues() {
  const res = await gh(`/issues?labels=${LABEL}&state=open`);
  if (!res.ok) return [];
  const issues = await res.json();
  return Array.isArray(issues) ? issues : [];
}

async function ensureLabel() {
  const res = await gh('/labels', {
    method: 'POST',
    body: JSON.stringify({ name: LABEL, color: '5319e7', description: 'Automated code-scanning configuration health findings' }),
  });
  if (!res.ok && res.status !== 422) console.warn(`Label create returned ${res.status}`);
}

async function report(findings) {
  const today = new Date().toISOString().slice(0, 10);
  const body = `## Code Scanning Health — ${today}\n\n${findings.map(f => `- ${f}`).join('\n')}\n\n---\n*Generated by the [Workflow Health Guard](../../actions/workflows/workflow-health.yml). Orphaned tools are cleared automatically; a live tool reporting errors needs a human to fix or remove its workflow.*`;
  const open = await getOpenIssues();
  if (open.length > 0) {
    const res = await gh(`/issues/${open[0].number}/comments`, { method: 'POST', body: JSON.stringify({ body }) });
    if (!res.ok) throw new Error(`Comment failed: ${res.status} ${await res.text()}`);
    console.log(`Appended findings to existing issue #${open[0].number}`);
    return;
  }
  await ensureLabel();
  const res = await gh('/issues', {
    method: 'POST',
    body: JSON.stringify({ title: `Code Scanning Health: attention needed [${today}]`, body, labels: [LABEL] }),
  });
  if (!res.ok) throw new Error(`Issue create failed: ${res.status} ${await res.text()}`);
  console.log(`Issue created: ${(await res.json()).html_url}`);
}

async function closeOpenIssues() {
  for (const issue of await getOpenIssues()) {
    await gh(`/issues/${issue.number}`, {
      method: 'PATCH',
      body: JSON.stringify({ state: 'closed', state_reason: 'completed' }),
    });
    console.log(`Code scanning config healthy — closed issue #${issue.number}`);
  }
}

async function main() {
  const tools = await collectTools();
  if (tools.size === 0) {
    console.log('No code-scanning analyses found — nothing to guard.');
    await closeOpenIssues();
    return;
  }
  const heartbeat = Math.max(...[...tools.values()].map(t => t.newest));
  const findings = [];
  let needsHuman = false;

  for (const t of tools.values()) {
    const lagDays = (heartbeat - t.newest) / 86400000;
    if (lagDays > STALE_DAYS) {
      const deleted = await deleteToolAnalyses(t.newestId);
      findings.push(`**Auto-remediated:** \`${t.name}\` was orphaned — its newest analysis lagged the active scanner by ${Math.floor(lagDays)} days (threshold ${STALE_DAYS}). Deleted ${deleted} stale ${deleted === 1 ? 'analysis' : 'analyses'}, clearing the "configuration error".`);
      console.log(`${t.name}: orphaned (lag ${Math.floor(lagDays)}d) -> deleted ${deleted}`);
    } else if (t.errored) {
      findings.push(`**Live tool erroring:** \`${t.name}\` is still active but a recent analysis reported an error. Fix the scanner's workflow or remove it — not auto-deleted (it may still be wanted).`);
      console.log(`${t.name}: live but erroring — flagged`);
      needsHuman = true;
    } else {
      console.log(`${t.name}: healthy (${t.count} analyses, newest lag ${lagDays.toFixed(1)}d)`);
    }
  }

  if (findings.length === 0) {
    await closeOpenIssues();
    console.log('Code scanning configuration healthy.');
    return;
  }
  await report(findings);
  if (needsHuman) process.exit(1);
}

main().catch(err => { console.error(err); process.exit(1); });
